# 1️⃣1️⃣ Find the sum of all elements in a list.
nums = [10,20,30,40,50]
sum = 0

for num in nums:
    sum += num

print(sum)

# 1️⃣2️⃣ Find the maximum and minimum value in a list (no max() / min()).
nums = [10,200,30,40,50]
max_value = nums[0]
for i in nums:
    if i > max_value:
        max_value = i

print(max_value)

